"""Baseline vs. optimized control: closed-loop comparison report.

    python -m experiments.comparison                       # winter + summer week, report to stdout
    python -m experiments.comparison --report docs/results/optimization_comparison.md

Each case runs the baseline and the optimized controller on the same
simulated week (same seed: identical occupancy and weather). The optimized
run is repeated with two forecast bases: the deployed ML model (if trained)
and the measured current power. All numbers are computed from the runs.
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
import time
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path

from config import SimulatorSettings, get_config
from experiments.scenarios import ScenarioResult, compare, make_optimizer, run_scenario
from ml.features import BUILDING_SPEC
from ml.registry import ModelNotFoundError, load_bundle
from utils.logging_config import configure_logging

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class Case:
    name: str
    start: datetime
    seed: int
    days: float = 7.0


# Held-out evaluation weeks: not used while developing the controller
# (development used 2026-01-12, seed 11).
CASES = [Case("winter week", datetime(2026, 1, 19, tzinfo=timezone.utc), 101),
         Case("summer week", datetime(2026, 7, 13, tzinfo=timezone.utc), 102)]


def run_case(case: Case, *, use_ml: bool, ml_only: bool = False) -> list[ScenarioResult]:
    config = get_config()
    sim = SimulatorSettings(interval_seconds=1, speed_factor=300, random_seed=case.seed,
                            start_time=case.start, building_id=config.SIMULATOR.building_id)
    results = [run_scenario("baseline", sim, case.days)]
    optimizer = make_optimizer(config.OPTIMIZATION)
    if not ml_only:
        results.append(run_scenario("optimized (measured basis)", sim, case.days, optimizer=optimizer))
    if use_ml:
        bundle = load_bundle(BUILDING_SPEC.name)
        results.append(run_scenario(f"optimized (ML basis, {bundle.version})", sim, case.days,
                                    optimizer=optimizer, bundle=bundle))
    return results


def render(cases: list[tuple[Case, list[ScenarioResult]]], settings) -> str:
    lines = [
        "# HVAC and lighting optimization: baseline vs. optimized",
        "",
        f"Generated by `python -m experiments.comparison` on {datetime.now(timezone.utc).isoformat()}. "
        "All values are computed from closed-loop simulations; baseline and optimized runs of a "
        "case share the same seed (identical occupancy and weather).",
        "",
        "* Simulation: 5 zones, 5-minute readings, 7 days per case.",
        "* Carbon: **synthetic** grid-intensity profile (`MockCarbonProvider`), identical for both runs.",
        f"* Optimizer: SciPy SLSQP every {settings.decision_interval_s:.0f} s per zone and on occupancy "
        f"changes; comfort band {settings.comfort_min_c}-{settings.comfort_max_c} °C (occupied), "
        f"setback {settings.setback_min_c}-{settings.setback_max_c} °C, max step "
        f"{settings.max_setpoint_step_c} °C; weights energy {settings.energy_weight_per_kwh}/kWh, "
        f"carbon {settings.carbon_weight_per_kg}/kg, comfort {settings.comfort_weight}.",
        "* Comfort compliance: share of occupied readings (excluding the server room) with "
        "temperature in 20-25 °C. Under-lit: occupied readings below 95 % of the required lux.",
        "",
    ]
    for case, results in cases:
        baseline = results[0]
        lines += [f"## {case.name} (start {case.start.date()}, seed {case.seed})", "",
                  "| Scenario | Energy (kWh) | Saving | CO₂e (kg) | Reduction | Peak (kW) | Peak red. | "
                  "Comfort compliance | Discomfort (°C·h) | Under-lit readings (on arrival) | Server max (°C) |",
                  "|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in results:
            c = compare(baseline, r)
            lines.append(
                f"| {r.name} | {r.energy_kwh:.1f} | {c['energy_saving_pct']:.1f} % | {r.carbon_kg:.1f} | "
                f"{c['carbon_reduction_pct']:.1f} % | {r.peak_power_kw:.1f} | {c['peak_reduction_pct']:.1f} % | "
                f"{r.comfort_compliance_pct:.1f} % | {r.discomfort_degree_hours:.1f} | "
                f"{r.lighting_shortfall_readings} of {r.occupied_readings} ({r.lighting_shortfall_on_arrival}) | "
                f"{r.server_max_temperature_c:.1f} |")
        lines += ["", "Energy by zone (kWh):", "",
                  "| Scenario | " + " | ".join(baseline.energy_by_zone_kwh) + " |",
                  "|---|" + "---|" * len(baseline.energy_by_zone_kwh)]
        for r in results:
            lines.append(f"| {r.name} | " + " | ".join(f"{v:.1f}" for v in r.energy_by_zone_kwh.values()) + " |")
        lines += ["", "Decisions: " + "; ".join(
            f"{r.name}: {r.decisions} decisions, {r.commands_applied} applied, {r.decisions_rejected} rejected"
            for r in results[1:]), ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m experiments.comparison", description=__doc__.splitlines()[0])
    parser.add_argument("--report", type=Path, help="write the Markdown report here")
    parser.add_argument("--json", type=Path, help="write raw results as JSON")
    parser.add_argument("--days", type=float, default=7.0)
    parser.add_argument("--no-ml", action="store_true", help="skip the ML-basis runs")
    args = parser.parse_args(argv)
    config = get_config()
    configure_logging(config.LOGGING, "experiments", stream=sys.stderr)

    use_ml = not args.no_ml
    if use_ml:
        try:
            load_bundle(BUILDING_SPEC.name)
        except ModelNotFoundError as exc:
            logger.warning("No building model; running without ML basis", extra={"error": str(exc)})
            use_ml = False
    cases = []
    for case in CASES:
        case = Case(case.name, case.start, case.seed, args.days)
        started = time.perf_counter()
        cases.append((case, run_case(case, use_ml=use_ml)))
        logger.info("Case finished", extra={"case": case.name,
                                            "seconds": round(time.perf_counter() - started, 1)})
    report = render(cases, config.OPTIMIZATION)
    print(report)
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(report, encoding="utf-8")
    if args.json:
        args.json.write_text(json.dumps({c.name: [r.as_dict() for r in rs] for c, rs in cases},
                                        indent=2, default=str), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
